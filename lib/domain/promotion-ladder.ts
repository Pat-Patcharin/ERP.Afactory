/* ============================================================
   ขั้นบันไดของแถม — หาชุดที่ให้ของแถมสูงสุดจริง

   สเปค §3.1 ตัดสินไว้สามข้อ และสามข้อนี้รวมกันเป็นตัวกำหนดว่า
   ต้องเขียนด้วยวิธีไหน:

     · ขั้นผสมกันได้        — ใช้ 10 กับ 3 พร้อมกันในใบเดียวได้
     · ขั้นเดียวกันใช้ซ้ำได้  — จ่าย 20 ใช้ขั้น 10 สองรอบได้
     · เศษที่จับคู่ไม่ได้ทิ้ง — ไม่ปัดขึ้น ไม่โมเมให้ถึงขั้น

   นั่นคือ unbounded knapsack ตรง ๆ ไม่ใช่ปัญหาที่ heuristic ตอบได้

   ทำไมไล่จากขั้นใหญ่ลงมาไม่พอ — สองแบบ ผิดคนละจังหวะ:

     หยิบขั้นใหญ่สุดแล้วจบ
       3 แถม 1 · 10 แถม 4 · 30 แถม 15 · จ่าย 13
       → หยิบขั้น 10 ได้ 4 แล้วทิ้งเศษ 3 ทั้งที่เศษนั้นครบขั้นพอดี
       ที่ถูกคือ 10 + 3 = แถม 5

     หยิบขั้นใหญ่แล้วเก็บเศษต่อ (ดูฉลาดกว่า แต่ยังผิด)
       3 แถม 1 · 5 แถม 1 · จ่าย 6
       → หยิบ 5 ได้ 1 เหลือ 1 จับคู่ไม่ได้ = แถม 1
       ที่ถูกคือ 3 สองรอบ = แถม 2

   ทั้งสองแบบดูเหมือนทำงานปกติ ให้คำตอบที่สมเหตุสมผลทุกครั้ง และ
   ไม่มีอะไรบอกว่าลูกค้าได้ของแถมน้อยกว่าที่ควร นั่นคือเหตุผลที่มันเป็น
   DP ไม่ใช่ลูป — ไม่ใช่เพราะ DP สวยกว่า แต่เพราะข้อผิดพลาดแบบนี้
   ไม่มีใครเห็น

   ไม่มี UI ในไฟล์นี้ และไม่มีการอ่านราคา — ตรงนี้ตอบคำถามเดียว
   คือ "จ่าย n ได้แถมกี่ชิ้น และมาจากขั้นไหนบ้าง" การเฉลี่ยราคา
   การตรวจ price_last และการเลือกโปรที่คุ้มที่สุด เป็นคนละขั้น
   ============================================================ */

export interface LadderTier {
  /** ซื้อ (จ่ายจริง) — จำนวนที่ลูกค้าออกเงิน ไม่นับของแถม */
  buy: number;
  /** แถม — จำนวนที่ได้เพิ่มเมื่อครบขั้นนี้หนึ่งรอบ */
  free: number;
}

/** ขั้นหนึ่งขั้น กับจำนวนรอบที่ใช้ */
export interface LadderUse {
  tier: LadderTier;
  times: number;
}

export interface LadderResult {
  /** ของแถมรวม */
  free: number;
  /**
   * ขั้นที่ใช้จริง เรียงจากขั้นใหญ่ลงเล็ก
   *
   * มีเพราะหน้าจอต้องบอกได้ว่าของแถมมาจากไหน — ตัวเลขเดี่ยว ๆ
   * ที่อธิบายตัวเองไม่ได้ คือตัวเลขที่เซลล์ไม่กล้าเอาไปคุยกับลูกค้า
   */
  uses: LadderUse[];
  /** จำนวนที่จับคู่ไม่ได้ — ทิ้งตาม §3.1 ไม่ปัดขึ้น */
  unmatched: number;
}

/**
 * ขั้นที่คำนวณได้จริง
 *
 * `buy` ต้องเป็นจำนวนเต็มบวก — ขั้นที่ซื้อ 0 แล้วได้ของแถมคือของแถมไม่จำกัด
 * และจะทำให้ DP วนไม่รู้จบ ขั้นที่ตกเกณฑ์ถูกข้าม ไม่ใช่ทำให้ทั้งก้อนพัง
 * เพราะฟอร์มเป็นคนตรวจว่าคนกรอกกรอกอะไรมา ที่นี่แค่ต้องไม่ระเบิด
 */
const usable = (tiers: readonly LadderTier[]): LadderTier[] =>
  tiers.filter(
    (t) =>
      Number.isInteger(t.buy) &&
      t.buy > 0 &&
      Number.isInteger(t.free) &&
      t.free >= 0,
  );

/**
 * ของแถมสูงสุดที่จำนวนซึ่งจ่ายจริงนี้ทำได้ และมาจากขั้นไหนบ้าง
 *
 * ใช้หน่วยความจำ O(paidQty) — ผู้เรียกเป็นคนคุมว่าจำนวนที่ส่งเข้ามาสมเหตุสมผล
 * ฟังก์ชันนี้ไม่ตั้งเพดานเอง เพราะเพดานจำนวนสั่งซื้อเป็นกติกาธุรกิจ
 * ไม่ใช่รายละเอียดของตัวคำนวณ
 */
export function bestLadder(
  tiers: readonly LadderTier[],
  paidQty: number,
): LadderResult {
  const qty = Number.isFinite(paidQty) ? Math.floor(paidQty) : 0;
  if (qty <= 0) return { free: 0, uses: [], unmatched: 0 };

  const steps = usable(tiers);
  if (!steps.length) return { free: 0, uses: [], unmatched: qty };

  /* best[q] = ของแถมสูงสุดที่ q หน่วยจ่ายจริงทำได้
     from[q] = ขั้นที่ใช้ตรงจุดนั้น · null เมื่อหน่วยที่ q ถูกทิ้งเป็นเศษ */
  const best = new Array<number>(qty + 1).fill(0);
  const from = new Array<number | null>(qty + 1).fill(null);

  for (let q = 1; q <= qty; q++) {
    /* ตั้งต้นด้วย "ทิ้งหนึ่งหน่วย"
       ซื่อสัตย์กับตัวเองไว้ก่อน: บรรทัดนี้ **ไม่ได้เปลี่ยนคำตอบ** ถ้าเขียน
       best[q] = 0 แทน ผลลัพธ์ทุกช่องเท่ากันเป๊ะ เพราะกฎเศษทิ้งของ §3.1
       ถูกบังคับด้วย base case อยู่แล้ว — จำนวนที่ไม่มีขั้นไหนรับได้จะได้ 0
       และการเวียนซ้ำเข้าไปหา best[q − buy] ก็เก็บเศษข้างในไปเอง
       (ยืนยันด้วยการลบบรรทัดนี้ทิ้งแล้วรัน — เขียวครบ 23 ตัว)

       เก็บไว้เพราะมันทำให้ from[q] === null อ่านออกตรง ๆ ว่า "หน่วยนี้ถูกทิ้ง"
       ซึ่งเป็นสิ่งที่การเดินย้อนกลับข้างล่างใช้นับ unmatched และทำให้เห็นด้วยตา
       ว่าของแถมไม่มีวันลดลงเมื่อจ่ายเพิ่ม */
    best[q] = best[q - 1];
    from[q] = null;

    for (let i = 0; i < steps.length; i++) {
      const t = steps[i];
      if (t.buy > q) continue;
      const gain = t.free + best[q - t.buy];
      if (gain > best[q]) {
        best[q] = gain;
        from[q] = i;
      }
    }
  }

  /* เดินย้อนกลับเพื่อบอกว่าใช้ขั้นไหนบ้าง */
  const times = new Map<number, number>();
  let unmatched = 0;
  for (let q = qty; q > 0; ) {
    const i = from[q];
    if (i === null) {
      unmatched++;
      q--;
      continue;
    }
    times.set(i, (times.get(i) ?? 0) + 1);
    q -= steps[i].buy;
  }

  const uses = [...times.entries()]
    .map(([i, n]) => ({ tier: steps[i], times: n }))
    .sort((a, b) => b.tier.buy - a.tier.buy);

  return { free: best[qty], uses, unmatched };
}
