/**
 * Credit Note (CN) — the financial adjustment raised after an approved
 * customer return, reducing what the customer owes us.
 *
 *   Sales Return → Return QC → Disposition → Credit Note → Receive Payment
 *
 * Credit Note NEVER touches stock. Inventory was already settled by Return
 * Receiving, Return QC and Disposition. Nothing here posts to a ledger either —
 * AR posting, journals and tax filing belong to the future Finance module.
 *
 * Mock dataset; mutating these arrays is how the prototype persists changes.
 */

export interface CnLine {
  line: number;
  code: string;
  name: string;
  /** Quantity on the source document (invoice line or shipped qty). */
  sourceQty: number;
  returnedQty: number;
  /** Quantity the return approved — the ceiling for creditQty. */
  approvedQty: number;
  creditQty: number;
  unit: string;
  unitPrice: number;
  /** Percent off the unit price, carried from the source document. */
  disc: number;
  taxCode: string;
  taxRate: number;
  reason: string;
  note: string;
}

export interface CnApprovalStep {
  step: string;
  role: string;
  approver: string;
  status: string;
  requestedAt: string;
  respondedAt: string;
  comment: string;
}

