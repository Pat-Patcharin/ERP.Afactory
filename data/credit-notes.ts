const ln = (
  n: number,
  code: string,
  name: string,
  unit: string,
  price: number,
  sourceQty: number,
  approvedQty: number,
  creditQty: number,
  opts: Partial<CnLine> = {},
): CnLine => ({
  line: n,
  code,
  name,
  sourceQty,
  returnedQty: approvedQty,
  approvedQty,
  creditQty,
  unit,
  unitPrice: price,
  disc: 0,
  taxCode: "VAT7",
  taxRate: 7,
  reason: "Customer Return",
  note: "",
  ...opts,
});

const step = (
  s: string,
  role: string,
  approver: string,
  status: string,
  requestedAt: string,
  respondedAt = "",
  comment = "",
): CnApprovalStep => ({ step: s, role, approver, status, requestedAt, respondedAt, comment });

const hist = (t: string, d: string, u: string, when: string, kind = "primary") => ({ t, d, u, when, kind });

