/**
 * Sales Invoice — the billing document raised against a customer once goods or
 * services are confirmed for billing.
 *
 *   Sales Order / Delivery Order / Shipment / Manual → Sales Invoice
 *
 *   Draft → Pending Review → Approved → Issued → Partially Paid → Paid
 *                                     → Cancelled / Void / Credited
 *
 * An invoice NEVER reserves or deducts stock. Stock movement stays with
 * Picking, Delivery Order and Shipment. Posting, payment and credit notes are
 * placeholders in Phase 1.
 *
 * Mock dataset; mutating these arrays is how the prototype persists changes.
 */

export interface InvLine {
  line: number;
  code: string;
  name: string;
  desc: string;
  /** Line on the source document this was billed from. */
  sourceLine: number;
  orderedQty: number;
  deliveredQty: number;
  prevInvoicedQty: number;
  invoiceQty: number;
  unit: string;
  unitPrice: number;
  discType: string;
  disc: number;
  taxCode: string;
  taxRate: number;
  warehouse: string;
  lotSerial: string;
  note: string;
  /** Set when the biller overrode the price that came from the source. */
  priceOverride: boolean;
  overrideReason: string;
  /** Salesperson's own name for the line. Blank falls back to `name` —
   *  read it through displayName(), never directly. */
  customName?: string;
  /** Whether customName and note reach customer-facing paper. Undefined = yes. */
  showOnBill?: boolean;
}

export interface SalesInvoice {
  code: string;
  customer: string;
  customerCode: string;
  customerType: string;
  taxId: string;
  billingAddress: string;
  contactPerson: string;
  phone: string;
  email: string;

  invoiceDate: string;
  dueDate: string;
  status: string;
  paymentStatus: string;
  approvalStatus: string;

  sourceType: string;
  sourceDoc: string;
  customerPo: string;
  referenceNo: string;

  branch: string;
  channel: string;
  salesRep: string;
  currency: string;
  fx: number;

  priceList: string;
  payTerm: string;
  creditDays: number;
  creditStatus: string;
  customerGroup: string;
  customerTier: string;

  /* Billing & tax */
  taxInvoiceType: string;
  branchNo: string;
  billingName: string;
  taxMode: string;
  vatRate: number;
  headerDisc: number;
  freight: number;
  otherCharges: number;
  rounding: number;
  withholdingTax: number;

  /* Payment placeholders — the Finance module owns these for real. */
  paidAmount: number;
  lastPaymentDate: string;
  paymentRef: string;
  paymentMethod: string;
  nextFollowUp: string;
  collectionNote: string;

  /**
   * The shipment this invoice's goods travelled on — a pointer, never a copy.
   *
   * The carrier, the tracking number, the delivery status and the date it
   * actually arrived all live on the shipment and are read from there through
   * `invoiceShipping()`. Deliberately NOT stored again here.
   *
   * Same reasoning as `effectiveBillType`: two copies of one fact drift, and
   * the day they disagree nobody can tell which is the truth. A tracking
   * number is worse than most, because the wrong one sends a customer to a
   * carrier's site that says the parcel does not exist.
   */
  shipmentRef?: string;

  cancelReason: string;
  voidReason: string;
  voidBy: string;
  creditNoteRef: string;

  note: string;
  items: InvLine[];
  history: { t: string; d: string; u: string; when: string; kind: string }[];
  audit: { event: string; user: string; when: string; field: string; from: string; to: string; kind: string }[];
  created: string;
  createdBy: string;
  updated: string;
  updatedBy: string;
}

